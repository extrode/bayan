using System.Globalization;
using System.Text;
using Bayan.Lowering;
using Bayan.Semantics.Binding;
using Bayan.Semantics.Symbols;
using Bayan.Syntax.Ast;
using ArrayType = Bayan.Semantics.Symbols.ArrayType;
using OptionalType = Bayan.Semantics.Symbols.OptionalType;
using TupleType = Bayan.Semantics.Symbols.TupleType;

namespace Bayan.Backend.C;

/// <summary>Writes a <see cref="LoweredProgram"/> as one C11 translation unit that includes <c>bayan-rt.h</c>.</summary>
public sealed class CEmitter
{
    private readonly LoweredProgram _program;
    private readonly string _packageRoot;

    // Named C types (structs for optionals, spans, lists, arrays, tuples and user structs), by C name.
    private readonly Dictionary<string, TypeSymbol> _types = new(StringComparer.Ordinal);
    private readonly List<string> _typeOrder = new();

    // Generated helper functions: prototype and definition, by name.
    private readonly Dictionary<string, (string Proto, string Body)> _helpers = new(StringComparer.Ordinal);
    private readonly List<string> _helperOrder = new();

    private readonly Dictionary<string, string> _files = new(StringComparer.Ordinal);
    private readonly Dictionary<FunctionSymbol, int> _testIndex = new();

    private static readonly HashSet<string> CKeywords = new(StringComparer.Ordinal)
    {
        "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else", "enum", "extern",
        "float", "for", "goto", "if", "inline", "int", "long", "register", "restrict", "return", "short", "signed",
        "sizeof", "static", "struct", "switch", "typedef", "union", "unsigned", "void", "volatile", "while",
        "bool", "true", "false", "main", "errno", "stdin", "stdout", "stderr", "NULL", "asm", "typeof",
    };

    private CEmitter(LoweredProgram program)
    {
        _program = program;
        _packageRoot = program.Compilation.PackageRoot;
        for (var i = 0; i < program.Tests.Count; i++) _testIndex[program.Tests[i].Function.Symbol] = i;
    }

    public static string Emit(LoweredProgram program) => new CEmitter(program).Run();

    private string Run()
    {
        var bodies = new StringBuilder();
        var protos = new StringBuilder();
        var functions = _program.Functions.Concat(_program.Tests.Select(t => t.Function)).ToList();
        foreach (var f in functions)
        {
            var emitter = new FunctionEmitter(this, f);
            protos.Append(emitter.Signature()).Append(";\n");
            bodies.Append(emitter.Emit()).Append('\n');
        }
        var main = EmitMain();

        var errors = new StringBuilder();
        var variants = _program.Compilation.ErrorVariants;
        errors.Append("static const byn_str byn_errors[] = {\n");
        if (variants.Count == 0) errors.Append("    BYN_STR(\"\", 0),\n");
        foreach (var v in variants) errors.Append("    ").Append(StringLiteral(v.Summary)).Append(",\n");
        errors.Append("};\n\n");
        errors.Append("static void byn_w_error(byn_writer* w, uint32_t code) {\n");
        errors.Append($"    if (code == 0 || code > {variants.Count}) byn_w_str(w, BYN_STR(\"no error\", 8));\n");
        errors.Append("    else byn_w_str(w, byn_errors[code - 1]);\n}\n\n");

        var types = EmitTypes();

        var sb = new StringBuilder();
        sb.Append("/* Generated by the Bayan compiler. Do not edit. */\n");
        sb.Append("#include \"bayan-rt.h\"\n#include <math.h>\n#include <stdlib.h>\n\n");
        foreach (var (path, name) in _files)
            sb.Append($"static const char {name}[] = {CString(path)};\n");
        sb.Append('\n').Append(types).Append(errors);
        sb.Append(protos).Append('\n');
        foreach (var h in _helperOrder) sb.Append(_helpers[h].Proto).Append(";\n");
        sb.Append('\n');
        foreach (var h in _helperOrder) sb.Append(_helpers[h].Body).Append('\n');
        sb.Append(bodies).Append(main);
        return sb.ToString();
    }

    private string EmitMain()
    {
        var sb = new StringBuilder();
        sb.Append("int main(int argc, char** argv) {\n    uint32_t err = 0;\n");
        if (_program.Tests.Count > 0)
        {
            sb.Append("    if (argc == 3 && strcmp(argv[1], \"--test\") == 0) {\n        switch (atoi(argv[2])) {\n");
            for (var i = 0; i < _program.Tests.Count; i++)
            {
                var fn = _program.Tests[i].Function.Symbol;
                sb.Append($"        case {i}: ").Append(fn.Fails ? "err = " : "").Append(FunctionName(fn)).Append("(); break;\n");
            }
            sb.Append("        default: return 2;\n        }\n");
            sb.Append("        if (err != 0) { byn_report_error(byn_errors[err - 1]); return 1; }\n");
            sb.Append("        byn_stdout_flush();\n        return 0;\n    }\n");
        }
        else
        {
            sb.Append("    (void)argv;\n");
        }
        sb.Append("    (void)argc;\n");
        if (_program.Main is { } main)
            sb.Append("    ").Append(main.Fails ? "err = " : "").Append(FunctionName(main)).Append("();\n");
        sb.Append("    if (err != 0) { byn_report_error(byn_errors[err - 1]); return 1; }\n");
        sb.Append("    byn_stdout_flush();\n    return 0;\n}\n");
        return sb.ToString();
    }

    // ── Names ────────────────────────────────────────────────────────────────────

    internal string FunctionName(FunctionSymbol f)
    {
        if (f.Kind == FunctionKind.Test) return "byn_test_" + _testIndex[f];
        var module = f.Module.CName;
        if (f.Kind == FunctionKind.Main) return $"byn_{module}__main";
        if (f.Owner is { } owner)
        {
            var member = f.Kind switch
            {
                FunctionKind.Constructor => "init" + owner.Constructors.IndexOf(f),
                FunctionKind.Getter => "get_" + f.Name,
                _ => f.Name,
            };
            return $"byn_{module}__{owner.Name}__{member}";
        }
        return $"byn_{module}__{f.Name}";
    }

    internal static string FieldName(string name) => CKeywords.Contains(name) ? name + "_" : name;

    internal string FileName(FunctionSymbol f)
    {
        var path = f.File?.Source.Path ?? "";
        // Project files are already relative to the project root; a loose file is named from its directory.
        var relative = Path.IsPathRooted(path) ? Path.GetRelativePath(_packageRoot, path).Replace('\\', '/') : path.Replace('\\', '/');
        if (relative.StartsWith("..", StringComparison.Ordinal)) relative = Path.GetFileName(path);
        if (!_files.TryGetValue(relative, out var name))
        {
            name = "byn_file_" + _files.Count;
            _files[relative] = name;
        }
        return name;
    }

    // ── Types ────────────────────────────────────────────────────────────────────

    internal string CType(TypeSymbol t) => t switch
    {
        PrimitiveType p => p.Kind switch
        {
            PrimitiveKind.I8 => "int8_t",
            PrimitiveKind.I16 => "int16_t",
            PrimitiveKind.I32 => "int32_t",
            PrimitiveKind.I64 or PrimitiveKind.Isize => "int64_t",
            PrimitiveKind.U8 => "uint8_t",
            PrimitiveKind.U16 => "uint16_t",
            PrimitiveKind.U32 or PrimitiveKind.Char => "uint32_t",
            PrimitiveKind.U64 or PrimitiveKind.Usize => "uint64_t",
            PrimitiveKind.F32 => "float",
            PrimitiveKind.F64 => "double",
            PrimitiveKind.Bool => "bool",
            PrimitiveKind.String => "byn_str",
            _ => "void",
        },
        ErrorSetSymbol or ErrorUnionType => "uint32_t",
        BuiltinType { Kind: BuiltinKind.Arena } => "byn_arena*",
        BuiltinType { Kind: BuiltinKind.StrBuf } => "byn_writer",
        _ => Named(t),
    };

    /// <summary>An identifier fragment naming a type, for generated type and helper names.</summary>
    internal string Key(TypeSymbol t) => t switch
    {
        PrimitiveType p => p.Kind == PrimitiveKind.String ? "str" : p.Name,
        ErrorSetSymbol or ErrorUnionType => "err",
        BuiltinType b => b.Kind == BuiltinKind.Arena ? "arena" : "strbuf",
        StructSymbol s => s.Module.CName + "__" + s.Name,
        OptionalType o => "opt_" + Key(o.Inner),
        ResultType r => "res_" + Key(r.Value),
        SpanType s => "span_" + Key(s.Element),
        ListType l => "list_" + Key(l.Element),
        ArrayType a => $"arr{a.Length}_" + Key(a.Element),
        TupleType tt => $"tup{tt.Fields.Count}_" + string.Join("_", tt.Fields.Select(f => Key(f.Type))),
        _ => throw new InvalidOperationException($"no C type for {t.DisplayName}"),
    };

    private string Named(TypeSymbol t)
    {
        var name = "bynt_" + Key(t);
        if (_types.TryAdd(name, t)) _typeOrder.Add(name);
        return name;
    }

    /// <summary>Forward typedefs for every named type, then the definitions with by-value members first.</summary>
    private string EmitTypes()
    {
        var defs = new StringBuilder();
        var done = new HashSet<string>(StringComparer.Ordinal);
        void Define(string name)
        {
            if (!done.Add(name)) return;
            var t = _types[name];
            var members = new List<(TypeSymbol Type, string Decl)>();
            switch (t)
            {
                case StructSymbol s:
                    foreach (var f in s.Fields) members.Add((f.Type, $"{CType(f.Type)} {FieldName(f.Name)}"));
                    if (s.Fields.Count == 0) members.Add((PrimitiveType.Bool, "char unused"));
                    break;
                case OptionalType o:
                    members.Add((PrimitiveType.Bool, "bool has"));
                    members.Add((o.Inner, $"{CType(o.Inner)} value"));
                    break;
                case ResultType r:
                    members.Add((PrimitiveType.U32, "uint32_t err"));
                    members.Add((r.Value, $"{CType(r.Value)} value"));
                    break;
                case SpanType sp:
                    members.Add((PrimitiveType.I64, $"{CType(sp.Element)}* ptr"));
                    members.Add((PrimitiveType.I64, "int64_t len"));
                    break;
                case ListType l:
                    members.Add((PrimitiveType.I64, $"{CType(l.Element)}* ptr"));
                    members.Add((PrimitiveType.I64, "int64_t len"));
                    members.Add((PrimitiveType.I64, "int64_t cap"));
                    members.Add((PrimitiveType.I64, "byn_alloc* alloc"));
                    break;
                case ArrayType a:
                    members.Add((a.Element, $"{CType(a.Element)} v[{a.Length}]"));
                    break;
                case TupleType tt:
                    for (var i = 0; i < tt.Fields.Count; i++) members.Add((tt.Fields[i].Type, $"{CType(tt.Fields[i].Type)} item{i + 1}"));
                    break;
            }
            foreach (var (type, _) in members)
                if (type is not PrimitiveType && CType(type) is var dep && _types.ContainsKey(dep)) Define(dep);
            defs.Append($"struct {name} {{\n");
            foreach (var (_, decl) in members) defs.Append("    ").Append(decl).Append(";\n");
            defs.Append("};\n\n");
        }
        // Defining a type can name new ones (an element type), so iterate to a fixed point.
        for (var i = 0; i < _typeOrder.Count; i++) Define(_typeOrder[i]);
        var sb = new StringBuilder();
        foreach (var name in _typeOrder) sb.Append($"typedef struct {name} {name};\n");
        sb.Append('\n').Append(defs);
        return sb.ToString();
    }

    // ── Helpers ──────────────────────────────────────────────────────────────────

    /// <summary>Registers a generated helper once; <paramref name="body"/> may register others.</summary>
    internal string Helper(string name, string proto, Func<string> body)
    {
        if (_helpers.ContainsKey(name)) return name;
        _helpers[name] = (proto, "");
        _helperOrder.Add(name);
        _helpers[name] = (proto, proto + " " + body());
        return name;
    }

    internal static string IntSuffix(TypeSymbol t) => ((PrimitiveType)t).Kind switch
    {
        PrimitiveKind.Isize => "i64",
        PrimitiveKind.Usize => "u64",
        var k => k.ToString().ToLowerInvariant(),
    };

    /// <summary><c>a == b</c> for any equatable type.</summary>
    internal string Equal(TypeSymbol t, string a, string b)
    {
        switch (t)
        {
            case PrimitiveType { IsString: true }:
                return $"byn_str_eq({a}, {b})";
            case PrimitiveType or ErrorSetSymbol or ErrorUnionType:
                return $"({a} == {b})";
        }
        var ct = CType(t);
        var name = "bynh_eq_" + Key(t);
        Helper(name, $"static bool {name}({ct} a, {ct} b)", () =>
        {
            if (t is ArrayType arr)
                return $"{{\n    for (int64_t i = 0; i < {arr.Length}; i++)\n        if (!{Equal(arr.Element, "a.v[i]", "b.v[i]")}) return false;\n    return true;\n}}\n";
            List<string> tests = t switch
            {
                OptionalType o => [$"a.has == b.has && (!a.has || {Equal(o.Inner, "a.value", "b.value")})"],
                ResultType r => [$"a.err == b.err && (a.err != 0 || {Equal(r.Value, "a.value", "b.value")})"],
                StructSymbol s => s.Fields.Select(f => Equal(f.Type, "a." + FieldName(f.Name), "b." + FieldName(f.Name))).ToList(),
                TupleType tt => tt.Fields.Select((f, i) => Equal(f.Type, $"a.item{i + 1}", $"b.item{i + 1}")).ToList(),
                _ => throw new InvalidOperationException($"no equality for {t.DisplayName}"),
            };
            return "{\n    return " + (tests.Count == 0 ? "true" : string.Join("\n        && ", tests)) + ";\n}\n";
        });
        return $"{name}({a}, {b})";
    }

    /// <summary>A statement that writes <paramref name="v"/> to the writer <c>w</c>.</summary>
    internal string Format(TypeSymbol t, string v, string w)
    {
        switch (t)
        {
            case PrimitiveType p:
                return p.Kind switch
                {
                    PrimitiveKind.String => $"byn_w_str({w}, {v});",
                    PrimitiveKind.F64 => $"byn_w_f64({w}, {v});",
                    PrimitiveKind.F32 => $"byn_w_f32({w}, {v});",
                    PrimitiveKind.Bool => $"byn_w_bool({w}, {v});",
                    PrimitiveKind.Char => $"byn_w_char({w}, {v});",
                    _ when p.IsSignedInteger => $"byn_w_i64({w}, (int64_t)({v}));",
                    _ => $"byn_w_u64({w}, (uint64_t)({v}));",
                };
            case ErrorSetSymbol or ErrorUnionType:
                return $"byn_w_error({w}, {v});";
        }
        var ct = CType(t);
        var name = "bynh_fmt_" + Key(t);
        Helper(name, $"static void {name}(byn_writer* w, {ct} v)", () =>
        {
            var sb = new StringBuilder("{\n");
            void Text(string s) => sb.Append($"    byn_w_str(w, {StringLiteral(s)});\n");
            switch (t)
            {
                case OptionalType o:
                    sb.Append($"    if (v.has) {Format(o.Inner, "v.value", "w")}\n");
                    sb.Append("    else byn_w_str(w, BYN_STR(\"null\", 4));\n");
                    break;
                case ResultType r:
                    sb.Append($"    if (v.err) byn_w_error(w, v.err);\n    else {Format(r.Value, "v.value", "w")}\n");
                    break;
                case StructSymbol s when FormatInto(s) is { } method:
                    sb.Append($"    {FunctionName(method)}(&v, w);\n");
                    break;
                case StructSymbol s:
                    Text(s.Fields.Count == 0 ? s.Name + " { }" : s.Name + " { ");
                    for (var i = 0; i < s.Fields.Count; i++)
                    {
                        Text((i > 0 ? ", " : "") + s.Fields[i].Name + ": ");
                        sb.Append("    ").Append(Format(s.Fields[i].Type, "v." + FieldName(s.Fields[i].Name), "w")).Append('\n');
                    }
                    if (s.Fields.Count > 0) Text(" }");
                    break;
                case TupleType tt:
                    Text("(");
                    for (var i = 0; i < tt.Fields.Count; i++)
                    {
                        if (i > 0) Text(", ");
                        sb.Append("    ").Append(Format(tt.Fields[i].Type, $"v.item{i + 1}", "w")).Append('\n');
                    }
                    Text(")");
                    break;
                default:
                    throw new InvalidOperationException($"cannot format {t.DisplayName}");
            }
            return sb.Append("}\n").ToString();
        });
        return $"{name}({w}, {v});";
    }

    private static FunctionSymbol? FormatInto(StructSymbol s) =>
        s.Methods.FirstOrDefault(m => m.Name == "formatInto" && !m.IsStatic && !m.Fails && m.Parameters.Count == 1
            && m.Parameters[0] is { IsByRef: true, Type: BuiltinType { Kind: BuiltinKind.StrBuf } });

    // ── Literals ─────────────────────────────────────────────────────────────────

    internal static string CString(string s) => "\"" + Escape(Encoding.UTF8.GetBytes(s)) + "\"";

    internal static string StringLiteral(string s)
    {
        var bytes = Encoding.UTF8.GetBytes(s);
        return $"BYN_STR(\"{Escape(bytes)}\", {bytes.Length})";
    }

    private static string Escape(byte[] bytes)
    {
        var sb = new StringBuilder();
        foreach (var b in bytes)
        {
            if (b is >= 0x20 and < 0x7F && b != '"' && b != '\\' && b != '?') sb.Append((char)b);
            else sb.Append('\\').Append(Convert.ToString(b, 8).PadLeft(3, '0'));
        }
        return sb.ToString();
    }

    internal string Constant(ConstantValue c, TypeSymbol type)
    {
        switch (c.Value)
        {
            case bool b:
                return b ? "true" : "false";
            case string s:
                return StringLiteral(s);
            case Rune r:
                return $"UINT32_C({r.Value})";
            case double d:
                return FloatLiteral(d, type == PrimitiveType.F32);
            case Int128 i when type.IsFloat:
                return FloatLiteral((double)i, type == PrimitiveType.F32);
            case Int128 i:
                return type is PrimitiveType p ? p.Kind switch
                {
                    PrimitiveKind.I64 or PrimitiveKind.Isize => i == long.MinValue ? "INT64_MIN" : $"INT64_C({i})",
                    PrimitiveKind.U64 or PrimitiveKind.Usize => $"UINT64_C({i})",
                    _ => $"(({CType(p)}){i})",
                } : $"(({CType(type)}){i})";
            default:
                throw new InvalidOperationException($"unexpected constant {c.Value}");
        }
    }

    private static string FloatLiteral(double d, bool single)
    {
        if (double.IsNaN(d)) return single ? "((float)NAN)" : "((double)NAN)";
        if (double.IsInfinity(d)) return (d < 0 ? "(-" : "(") + (single ? "(float)INFINITY)" : "(double)INFINITY)");
        var text = d.ToString("R", CultureInfo.InvariantCulture);
        if (!text.Contains('.') && !text.Contains('E')) text += ".0";
        return single ? $"((float){text})" : $"({text})";
    }
}

/// <summary>Emits one function body.</summary>
internal sealed class FunctionEmitter
{
    private readonly CEmitter _c;
    private readonly LoweredFunction _f;
    private readonly FunctionSymbol _fn;
    private readonly Dictionary<LocalSymbol, string> _names = new();
    private readonly StringBuilder _sb = new();
    private readonly string _file;
    private int _indent = 1;

    public FunctionEmitter(CEmitter c, LoweredFunction f)
    {
        _c = c;
        _f = f;
        _fn = f.Symbol;
        _file = c.FileName(_fn);
        foreach (var p in _fn.Parameters) _names[p] = "p_" + p.Name;
        var n = 0;
        foreach (var l in f.Locals)
            _names[l] = l.Kind == LocalKind.Temp ? "t" + n++ : "l" + n++ + "_" + l.Name;
    }

    private bool ReturnsValue => !_fn.ReturnType.IsVoid && !_fn.ReturnType.IsNever && _fn.Kind != FunctionKind.Constructor;

    public string Signature()
    {
        string result;
        if (_fn.Fails) result = "uint32_t";
        else if (_fn.Kind == FunctionKind.Constructor) result = _c.CType(_fn.Owner!);
        else result = _c.CType(_fn.ReturnType);
        var ps = new List<string>();
        if (_fn.HasThis && _fn.Kind != FunctionKind.Constructor) ps.Add($"{_c.CType(_fn.Owner!)}* self");
        foreach (var p in _fn.Parameters) ps.Add($"{_c.CType(p.Type)}{(p.IsByRef ? "*" : "")} {_names[p]}");
        if (_fn.Fails && ReturnsValue) ps.Add($"{_c.CType(_fn.ReturnType)}* byn_out");
        var noreturn = _fn.ReturnType.IsNever && !_fn.Fails ? "BYN_NORETURN " : "";
        return $"{noreturn}{result} {_c.FunctionName(_fn)}({(ps.Count == 0 ? "void" : string.Join(", ", ps))})";
    }

    public string Emit()
    {
        _sb.Append(Signature()).Append(" {\n");
        if (_fn.Kind == FunctionKind.Constructor)
        {
            var t = _c.CType(_fn.Owner!);
            Line($"{t} self_v = {{0}};");
            Line($"{t}* self = &self_v;");
        }
        foreach (var l in _f.Locals)
        {
            if (l.Type.IsVoid || l.Type.IsNever) continue;
            Line($"{_c.CType(l.Type)} {_names[l]} = {{0}};");
        }
        for (var i = 0; i < _f.ContextSlots; i++) Line($"byn_alloc* ctx{i} = byn_context;");
        foreach (var s in _f.Body.Statements) Statement(s);
        if (_fn.Kind == FunctionKind.Constructor) Line("return self_v;");
        else if (_fn.Fails && !ReturnsValue) Line("return 0;");
        else if (_fn.ReturnType.IsNever) Line($"byn_unreachable({_file}, {LineOf(_f.Body.Syntax)});");
        _sb.Append("}\n");
        return _sb.ToString();
    }

    private void Line(string text) => _sb.Append(' ', _indent * 4).Append(text).Append('\n');

    private int LineOf(Node syntax) => _fn.File is { } f ? f.Source.GetLinePosition(syntax.Span.Start).Line : 0;

    private string Loc(Node syntax) => $"{_file}, {LineOf(syntax)}";

    // ── Statements ───────────────────────────────────────────────────────────────

    private void Block(BoundStmt s)
    {
        _indent++;
        if (s is BoundBlock b) foreach (var inner in b.Statements) Statement(inner);
        else Statement(s);
        _indent--;
    }

    private void Statement(BoundStmt s)
    {
        switch (s)
        {
            case BoundBlock b:
                Line("{");
                Block(b);
                Line("}");
                break;
            case BoundExprStmt e:
                Line($"(void){Expr(e.Expr)};");
                break;
            case BoundAssign a:
                Line($"{Expr(a.Target)} = {Expr(a.Value)};");
                break;
            case BoundIf i:
                Line($"if ({Expr(i.Condition)}) {{");
                Block(i.Then);
                if (i.Else is not null)
                {
                    Line("} else {");
                    Block(i.Else);
                }
                Line("}");
                break;
            case LLoop l:
                Line("for (;;) {");
                Block(l.Body);
                Line("}");
                break;
            case LLabel l:
                _sb.Append(' ', Math.Max(0, _indent - 1) * 4).Append(l.Name).Append(":;\n");
                break;
            case LGoto g:
                Line($"goto {g.Label};");
                break;
            case LReturn r:
                Return(r);
                break;
            case LReturnError e:
                Line($"return {Expr(e.Code)};");
                break;
            case LFailingCall f:
            {
                var result = f.Result is null ? null : "&" + _names[f.Result];
                Line($"{_names[f.Error]} = {Call(f.Call, result)};");
                break;
            }
            case LWrite w:
                Write(w);
                break;
            case LPanic p:
                Line($"byn_panic({CEmitter.CString(p.Message)}, {Loc(p.Syntax)});");
                break;
            case LSetContext c when c.Arena is { } arena:
                Line($"ctx{c.Slot} = byn_context;");
                Line($"byn_context = byn_arena_alloc({Expr(arena)});");
                break;
            case LSetContext c:
                Line($"byn_context = ctx{c.Slot};");
                break;
            case LFreeArena f:
                Line($"byn_arena_free({Expr(f.Arena)});");
                break;
            default:
                throw new InvalidOperationException($"cannot emit {s.GetType().Name}");
        }
    }

    private void Return(LReturn r)
    {
        if (_fn.Kind == FunctionKind.Constructor)
        {
            Line("return self_v;");
            return;
        }
        if (_fn.Fails)
        {
            if (r.Value is not null) Line($"*byn_out = {Expr(r.Value)};");
            Line("return 0;");
            return;
        }
        Line(r.Value is null ? "return;" : $"return {Expr(r.Value)};");
    }

    private void Write(LWrite w)
    {
        Line("{");
        _indent++;
        if (w.Sink == WriteSink.StrBuf)
        {
            Line($"byn_writer* w = &{Expr(w.Target!)};");
            Line($"w->file = {_file};");
            Line($"w->line = {LineOf(w.Syntax)};");
        }
        else
        {
            var mode = w.Sink == WriteSink.Print ? "BYN_WRITE_STDOUT" : "BYN_WRITE_TRUNCATE";
            Line("uint8_t wb[256];");
            Line($"byn_writer wv = {{wb, 256, 0, {mode}, {Loc(w.Syntax)}}};");
            Line("byn_writer* w = &wv;");
        }
        foreach (var part in w.Parts)
        {
            if (part.Text is { Length: > 0 } text) Line($"byn_w_str(w, {CEmitter.StringLiteral(text)});");
            else if (part.Value is { } value) Line(_c.Format(value.Type, Expr(value), "w"));
        }
        if (w.Sink == WriteSink.Print) Line("byn_w_println(w);");
        else if (w.Sink == WriteSink.Panic) Line($"byn_panic_str((byn_str){{wb, wv.len}}, {Loc(w.Syntax)});");
        _indent--;
        Line("}");
    }

    // ── Expressions ──────────────────────────────────────────────────────────────

    private string Expr(BoundExpr e)
    {
        if (e.Constant is { } c && e.Type is PrimitiveType { IsVoid: false, IsNever: false } && e is not BoundLocal { Local: ParameterSymbol })
            return _c.Constant(c, e.Type);
        switch (e)
        {
            case BoundLiteral l:
                return _c.Constant(l.Value, l.Type);
            case BoundDefault d:
                return $"(({_c.CType(d.Type)}){{0}})";
            case BoundLocal l:
                return l.Local is ParameterSymbol { IsByRef: true } ? $"(*{_names[l.Local]})" : _names[l.Local];
            case BoundThis:
                return "(*self)";
            case BoundField f:
                return $"{Expr(f.Receiver)}.{CEmitter.FieldName(f.Field.Name)}";
            case BoundTupleElement t:
                return $"{Expr(t.Receiver)}.item{t.Index + 1}";
            case BoundCall call:
                return Call(call, null);
            case BoundBuiltinCall b:
                return Builtin(b);
            case BoundUnary u:
                return Unary(u);
            case BoundBinary b:
                return Binary(b);
            case BoundConversion c2:
                return Conversion(c2);
            case BoundConditional c2:
                return $"({Expr(c2.Condition)} ? {Expr(c2.WhenTrue)} : {Expr(c2.WhenFalse)})";
            case BoundStructLiteral s:
                return s.Fields.Length == 0 ? $"(({_c.CType(s.Struct)}){{0}})" : $"(({_c.CType(s.Struct)}){{{string.Join(", ", s.Fields.Select(Expr))}}})";
            case BoundTuple t:
                return $"(({_c.CType(t.Type)}){{{string.Join(", ", t.Elements.Select(Expr))}}})";
            case BoundCollection { Type: ListType l }:
                return $"(({_c.CType(l)}){{NULL, 0, 0, byn_context}})";
            case BoundCollection { Type: ArrayType a } col:
                return col.Elements.Length == 0 ? $"(({_c.CType(a)}){{0}})" : $"(({_c.CType(a)}){{{{{string.Join(", ", col.Elements.Select(Expr))}}}}})";
            case BoundIndex i:
                return Index(i);
            case BoundSlice s:
                return Slice(s);
            case BoundErrorVariant v:
                return $"UINT32_C({v.Variant.Code})";
            case LOptionalHas h:
                return $"{Expr(h.Optional)}.has";
            case LOptionalValue v:
                return $"{Expr(v.Optional)}.value";
            case LAssignExpr a:
                return $"({Expr(a.Target)} = {Expr(a.Value)})";
            case LSequence s:
                return "(" + string.Join(", ", s.Effects.Select(Expr).Append(Expr(s.Value))) + ")";
            case LIndexUnchecked u:
                return u.Target.Type is ArrayType ? $"{Expr(u.Target)}.v[{Expr(u.Index)}]" : $"{Expr(u.Target)}.ptr[{Expr(u.Index)}]";
            case LNextChar n:
                return $"byn_str_next({Expr(n.Text)}, &{_names[n.Position]})";
            default:
                throw new InvalidOperationException($"cannot emit {e.GetType().Name}");
        }
    }

    private string Call(BoundCall c, string? result)
    {
        var fn = c.Function;
        var args = new List<string>();
        switch (fn.Builtin)
        {
            case BuiltinFunction.Print:
                return $"byn_print({Expr(c.Arguments[0])})";
            case BuiltinFunction.Panic:
                return $"byn_panic_str({Expr(c.Arguments[0])}, {Loc(c.Syntax)})";
            case BuiltinFunction.ArenaNew:
                return "byn_arena_new()";
            case BuiltinFunction.StrBufNew:
            {
                var span = _c.CType(fn.Parameters[0].Type);
                var name = _c.Helper("bynh_strbuf", $"static byn_writer bynh_strbuf({span} s, const char* file, int line)", () =>
                    "{\n    return (byn_writer){s.ptr, s.len, 0, BYN_WRITE_STRICT, file, line};\n}\n");
                return $"{name}({Expr(c.Arguments[0])}, {Loc(c.Syntax)})";
            }
        }
        if (fn.HasThis && fn.Kind != FunctionKind.Constructor) args.Add("&" + Expr(c.Receiver!));
        for (var i = 0; i < c.Arguments.Length; i++)
            args.Add(fn.Parameters[i].IsByRef ? "&" + Expr(c.Arguments[i]) : Expr(c.Arguments[i]));
        if (result is not null) args.Add(result);
        return $"{_c.FunctionName(fn)}({string.Join(", ", args)})";
    }

    private string Builtin(BoundBuiltinCall b)
    {
        var r = b.Receiver;
        var arg = b.Arguments.Length > 0 ? Expr(b.Arguments[0]) : "";
        switch (b.Member)
        {
            case BuiltinMember.StringLength or BuiltinMember.SpanLength or BuiltinMember.ListLength or BuiltinMember.StrBufLength:
                return $"{Expr(r)}.len";
            case BuiltinMember.StringIsEmpty or BuiltinMember.SpanIsEmpty or BuiltinMember.ListIsEmpty:
                return $"({Expr(r)}.len == 0)";
            case BuiltinMember.StringBytes:
            {
                var span = _c.CType(b.Type);
                var name = _c.Helper("bynh_str_bytes", $"static {span} bynh_str_bytes(byn_str s)", () => $"{{\n    return ({span}){{(uint8_t*)s.ptr, s.len}};\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.StringCopy:
                return $"byn_str_copy({Expr(r)}, byn_arena_alloc({arg}))";
            case BuiltinMember.StringStartsWith:
                return $"byn_str_starts_with({Expr(r)}, {arg})";
            case BuiltinMember.StringEndsWith:
                return $"byn_str_ends_with({Expr(r)}, {arg})";
            case BuiltinMember.StringContains:
                return $"byn_str_contains({Expr(r)}, {arg})";
            case BuiltinMember.SpanCopy:
            {
                var span = (SpanType)r.Type;
                var list = _c.CType(b.Type);
                var st = _c.CType(span);
                var et = _c.CType(span.Element);
                var name = "bynh_copy_" + _c.Key(span);
                _c.Helper(name, $"static {list} {name}({st} s, byn_alloc* a)", () =>
                    $"{{\n    {list} r = {{NULL, 0, 0, a}};\n    if (s.len > 0) {{\n        r.ptr = ({et}*)byn_copy_bytes(s.ptr, s.len * (int64_t)sizeof({et}), a);\n        r.len = r.cap = s.len;\n    }}\n    return r;\n}}\n");
                return $"{name}({Expr(r)}, byn_arena_alloc({arg}))";
            }
            case BuiltinMember.ListAdd:
            {
                var lt = _c.CType(r.Type);
                var et = _c.CType(((ListType)r.Type).Element);
                var name = "bynh_add_" + _c.Key(r.Type);
                _c.Helper(name, $"static void {name}({lt}* l, {et} v)", () =>
                    $"{{\n    if (!l->alloc) l->alloc = byn_context;\n    byn_list_reserve((void**)&l->ptr, &l->cap, l->len + 1, (int64_t)sizeof({et}), l->alloc);\n    l->ptr[l->len++] = v;\n}}\n");
                return $"{name}(&{Expr(r)}, {arg})";
            }
            case BuiltinMember.ListAsSpan:
            {
                var lt = _c.CType(r.Type);
                var st = _c.CType(b.Type);
                var name = "bynh_span_" + _c.Key(r.Type);
                _c.Helper(name, $"static {st} {name}({lt} l)", () => $"{{\n    return ({st}){{l.ptr, l.len}};\n}}\n");
                return $"{name}({Expr(r)})";
            }
            case BuiltinMember.ListClear or BuiltinMember.StrBufClear:
                return $"({Expr(r)}.len = 0)";
            case BuiltinMember.ListRemoveLast:
            {
                var lt = _c.CType(r.Type);
                var et = _c.CType(b.Type);
                var name = "bynh_pop_" + _c.Key(r.Type);
                _c.Helper(name, $"static {et} {name}({lt}* l, const char* file, int line)", () =>
                    $"{{\n    if (l->len == 0) byn_panic(\"removeLast on an empty list\", file, line);\n    return l->ptr[--l->len];\n}}\n");
                return $"{name}(&{Expr(r)}, {Loc(b.Syntax)})";
            }
            case BuiltinMember.ArrayLength:
                return $"((void){Expr(r)}, INT64_C({((ArrayType)r.Type).Length}))";
            case BuiltinMember.ArrayAsSpan:
                return $"(({_c.CType(b.Type)}){{{Expr(r)}.v, {((ArrayType)r.Type).Length}}})";
            case BuiltinMember.ArenaReset:
                return $"byn_arena_reset({Expr(r)})";
            case BuiltinMember.StrBufAppend:
                return $"byn_w_str(&{Expr(r)}, {arg})";
            case BuiltinMember.StrBufAsString:
                return $"byn_strbuf_str({Expr(r)})";
            case BuiltinMember.CharValue:
                return $"((uint32_t){Expr(r)})";
            case BuiltinMember.ResultIsOk:
                return $"({Expr(r)}.err == 0)";
            case BuiltinMember.ResultValue or BuiltinMember.ResultError:
            {
                var value = b.Member == BuiltinMember.ResultValue;
                var res = _c.CType(r.Type);
                var name = (value ? "bynh_value_" : "bynh_error_") + _c.Key(r.Type);
                var message = value ? "result holds an error" : "result holds a value";
                _c.Helper(name, $"static {_c.CType(b.Type)} {name}({res} r, const char* file, int line)", () =>
                    $"{{\n    if ({(value ? "r.err" : "!r.err")}) byn_panic(\"{message}\", file, line);\n    return {(value ? "r.value" : "r.err")};\n}}\n");
                return $"{name}({Expr(r)}, {Loc(b.Syntax)})";
            }
            default:
                throw new InvalidOperationException($"cannot emit {b.Member}");
        }
    }

    private string Unary(BoundUnary u)
    {
        var v = Expr(u.Operand);
        return u.Op switch
        {
            UnaryOp.Plus => v,
            UnaryOp.Negate when u.Type.IsInteger => $"byn_neg_{CEmitter.IntSuffix(u.Type)}({v}, {Loc(u.Syntax)})",
            UnaryOp.Negate => $"(-{v})",
            UnaryOp.Not => $"(!{v})",
            UnaryOp.Complement => $"(({_c.CType(u.Type)})~{v})",
            _ => throw new InvalidOperationException($"cannot emit unary {u.Op}"),
        };
    }

    private string Binary(BoundBinary b)
    {
        var l = Expr(b.Left);
        var r = Expr(b.Right);
        var t = b.Left.Type;
        if (t.IsInteger)
        {
            var n = CEmitter.IntSuffix(t);
            switch (b.Op)
            {
                case BinaryOp.Add: return $"byn_add_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Sub: return $"byn_sub_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Mul: return $"byn_mul_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Div: return $"byn_div_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.Rem: return $"byn_rem_{n}({l}, {r}, {Loc(b.Syntax)})";
                case BinaryOp.AddWrap: return $"byn_addw_{n}({l}, {r})";
                case BinaryOp.SubWrap: return $"byn_subw_{n}({l}, {r})";
                case BinaryOp.MulWrap: return $"byn_mulw_{n}({l}, {r})";
                case BinaryOp.AddSat: return $"byn_adds_{n}({l}, {r})";
                case BinaryOp.SubSat: return $"byn_subs_{n}({l}, {r})";
                case BinaryOp.MulSat: return $"byn_muls_{n}({l}, {r})";
                case BinaryOp.Shl: return $"byn_shl_{n}({l}, (int64_t)({r}))";
                case BinaryOp.Shr: return $"byn_shr_{n}({l}, (int64_t)({r}))";
                case BinaryOp.BitAnd: return $"(({_c.CType(t)})({l} & {r}))";
                case BinaryOp.BitOr: return $"(({_c.CType(t)})({l} | {r}))";
                case BinaryOp.BitXor: return $"(({_c.CType(t)})({l} ^ {r}))";
            }
        }
        if (t.IsFloat && b.Op == BinaryOp.Rem) return t == PrimitiveType.F32 ? $"fmodf({l}, {r})" : $"fmod({l}, {r})";
        if (t.IsString && b.Op is BinaryOp.Lt or BinaryOp.Gt or BinaryOp.Le or BinaryOp.Ge)
            return $"(byn_str_cmp({l}, {r}) {Op(b.Op)} 0)";
        return b.Op switch
        {
            BinaryOp.Eq => _c.Equal(t, l, r),
            BinaryOp.Ne => $"(!{_c.Equal(t, l, r)})",
            _ => $"({l} {Op(b.Op)} {r})",
        };
    }

    private static string Op(BinaryOp op) => op switch
    {
        BinaryOp.Add => "+", BinaryOp.Sub => "-", BinaryOp.Mul => "*", BinaryOp.Div => "/",
        BinaryOp.Lt => "<", BinaryOp.Gt => ">", BinaryOp.Le => "<=", BinaryOp.Ge => ">=",
        BinaryOp.BitAnd => "&", BinaryOp.BitOr => "|", BinaryOp.BitXor => "^",
        BinaryOp.LogicalAnd => "&&", BinaryOp.LogicalOr => "||",
        _ => throw new InvalidOperationException($"no C operator for {op}"),
    };

    private string Conversion(BoundConversion c)
    {
        var v = Expr(c.Operand);
        var from = c.Operand.Type;
        var to = c.Type;
        switch (c.Kind)
        {
            case ConversionKind.Identity or ConversionKind.FromNever:
                return v;
            case ConversionKind.Widen:
                return $"(({_c.CType(to)}){v})";
            case ConversionKind.NumericCast when to.IsInteger && from.IsFloat:
                return $"byn_f2i_{CEmitter.IntSuffix(to)}((double){v})";
            case ConversionKind.NumericCast or ConversionKind.CharToInteger when to.IsInteger:
                return from.IsSignedInteger
                    ? $"byn_cast_{CEmitter.IntSuffix(to)}_i((int64_t){v}, {Loc(c.Syntax)})"
                    : $"byn_cast_{CEmitter.IntSuffix(to)}_u((uint64_t){v}, {Loc(c.Syntax)})";
            case ConversionKind.NumericCast:
                return $"(({_c.CType(to)}){v})";
            case ConversionKind.IntegerToChar:
                return from.IsSignedInteger
                    ? $"byn_to_char((int64_t){v}, {Loc(c.Syntax)})"
                    : $"byn_to_char_u((uint64_t){v}, {Loc(c.Syntax)})";
            case ConversionKind.ToOptional:
                return $"(({_c.CType(to)}){{true, {v}}})";
            case ConversionKind.NullToOptional:
                return $"(({_c.CType(to)}){{0}})";
            case ConversionKind.ToResult:
                return $"(({_c.CType(to)}){{0, {v}}})";
            case ConversionKind.ErrorToResult:
                return $"(({_c.CType(to)}){{{v}}})";
            case ConversionKind.ListToSpan:
                return $"(({_c.CType(to)}){{{v}.ptr, {v}.len}})";
            case ConversionKind.StringToBytes:
                return $"(({_c.CType(to)}){{(uint8_t*){v}.ptr, {v}.len}})";
            case ConversionKind.ArrayToSpan:
                return $"(({_c.CType(to)}){{{v}.v, {((ArrayType)from).Length}}})";
            default:
                throw new InvalidOperationException($"cannot emit conversion {c.Kind}");
        }
    }

    private string Index(BoundIndex i)
    {
        var target = i.Target.Type;
        var et = _c.CType(i.Type);
        var tt = _c.CType(target);
        var name = "bynh_at_" + _c.Key(target);
        if (target is ArrayType a)
        {
            _c.Helper(name, $"static {et}* {name}({tt}* a, int64_t i, bool from_end, const char* file, int line)", () =>
                $"{{\n    if (from_end) i = {a.Length} - i;\n    return &a->v[byn_index(i, {a.Length}, file, line)];\n}}\n");
            return $"(*{name}(&{Expr(i.Target)}, (int64_t){Expr(i.Index)}, {(i.FromEnd ? "true" : "false")}, {Loc(i.Syntax)}))";
        }
        _c.Helper(name, $"static {et}* {name}({tt} s, int64_t i, bool from_end, const char* file, int line)", () =>
            "{\n    if (from_end) i = s.len - i;\n    return &s.ptr[byn_index(i, s.len, file, line)];\n}\n");
        return $"(*{name}({Expr(i.Target)}, (int64_t){Expr(i.Index)}, {(i.FromEnd ? "true" : "false")}, {Loc(i.Syntax)}))";
    }

    private string Slice(BoundSlice s)
    {
        var start = s.Start is null ? "0, 2" : $"(int64_t){Expr(s.Start)}, {(s.StartFromEnd ? 1 : 0)}";
        var end = s.End is null ? "0, 2" : $"(int64_t){Expr(s.End)}, {(s.EndFromEnd ? 1 : 0)}";
        var tail = $"{start}, {end}, {(s.Inclusive ? "true" : "false")}, {Loc(s.Syntax)}";
        var target = s.Target.Type;
        if (target.IsString)
        {
            var str = _c.Helper("bynh_slice_str",
                "static byn_str bynh_slice_str(byn_str s, int64_t a, int am, int64_t b, int bm, bool incl, const char* file, int line)",
                () => "{\n    int64_t from, to;\n    byn_slice_range(s.len, a, am, b, bm, incl, file, line, &from, &to);\n    return byn_str_slice(s, from, to, file, line);\n}\n");
            return $"{str}({Expr(s.Target)}, {tail})";
        }
        var st = _c.CType(s.Type);
        var tt = _c.CType(target);
        var name = "bynh_slice_" + _c.Key(target);
        var (param, len, ptr, arg) = target is ArrayType a
            ? ($"{tt}* x", a.Length.ToString(CultureInfo.InvariantCulture), "x->v", "&" + Expr(s.Target))
            : ($"{tt} x", "x.len", "x.ptr", Expr(s.Target));
        _c.Helper(name, $"static {st} {name}({param}, int64_t a, int am, int64_t b, int bm, bool incl, const char* file, int line)", () =>
            $"{{\n    int64_t from, to;\n    byn_slice_range({len}, a, am, b, bm, incl, file, line, &from, &to);\n    return ({st}){{{ptr} + from, to - from}};\n}}\n");
        return $"{name}({arg}, {tail})";
    }
