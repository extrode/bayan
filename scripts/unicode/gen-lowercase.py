#!/usr/bin/env python3
"""Regenerates the simple case mapping tables in src/runtime/bayan-rt.c (revision 0015).

Usage: python3 -I scripts/unicode/gen-lowercase.py [path/to/UnicodeData.txt]

Without a path it downloads UnicodeData.txt for UNICODE_VERSION into tmp/ucd-<version>/. The version is the one
.NET 10's CharUnicodeInfo carries, so `lowercased()` agrees with `ToLowerInvariant` there. The tables are the simple
mappings (UnicodeData.txt field 13 lowercase, field 12 uppercase), minus the dotted and dotless i, which .NET's
invariant casing leaves unchanged: U+0130 does not lowercase and U+0131 does not uppercase.
"""
import os
import sys
import urllib.request

UNICODE_VERSION = "16.0.0"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RUNTIME = os.path.join(ROOT, "src", "runtime", "bayan-rt.c")
BEGIN = "/* BEGIN generated by scripts/unicode/gen-lowercase.py"
END = "/* END generated by scripts/unicode/gen-lowercase.py */"
EXCLUDED_LOWER = {0x0130}
EXCLUDED_UPPER = {0x0131}


def load(path):
    lower, upper = [], []
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.rstrip("\n").split(";")
            cp = int(fields[0], 16)
            if fields[13] and cp not in EXCLUDED_LOWER:
                lower.append((cp, int(fields[13], 16)))
            if fields[12] and cp not in EXCLUDED_UPPER:
                upper.append((cp, int(fields[12], 16)))
    return lower, upper


def table(name, pairs):
    lines = [f"static const uint32_t {name}[][2] = {{"]
    for i in range(0, len(pairs), 6):
        lines.append("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in pairs[i:i + 6]))
    lines.append("};")
    return "\n".join(lines)


def cached_ucd():
    directory = os.path.join(ROOT, "tmp", f"ucd-{UNICODE_VERSION}")
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, "UnicodeData.txt")
    if not os.path.exists(path):
        # download beside the cache and move it in whole, so an interrupted download is never taken for the file
        urllib.request.urlretrieve(f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/UnicodeData.txt", path + ".part")
        os.replace(path + ".part", path)
    return path


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else cached_ucd()
    lower, upper = load(path)
    generated = "\n".join([
        f"{BEGIN} from UnicodeData.txt {UNICODE_VERSION}; do not edit. */",
        "/* Simple lowercase (field 13) and uppercase (field 12) mappings, sorted by code point; U+0130 and U+0131 map to",
        " * themselves, as in .NET's invariant casing. */",
        table("byn_lower_map", lower),
        table("byn_upper_map", upper),
        END,
    ])
    with open(RUNTIME, encoding="utf-8", newline="") as f:
        source = f.read()
    start, end = source.index(BEGIN), source.index(END) + len(END)
    with open(RUNTIME, "w", encoding="utf-8", newline="") as f:
        f.write(source[:start] + generated + source[end:])
    print(f"{len(lower)} lowercase, {len(upper)} uppercase mappings from {path}")


if __name__ == "__main__":
    main()
